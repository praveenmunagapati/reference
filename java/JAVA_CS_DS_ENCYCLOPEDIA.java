/**
 * Generics deep-dive: bounded type parameters, wildcards.
 *
 * <p>Wildcards:
 * <ul>
 *   <li>{@code ? extends T} — upper bound (read-only, producer)</li>
 *   <li>{@code ? super T} — lower bound (write-only, consumer)</li>
 *   <li>PECS: Producer Extends, Consumer Super</li>
 * </ul>
 */
static <T extends Comparable<T>> T findMax(List<T> list) {
    if (list.isEmpty()) throw new NoSuchElementException("Empty list");
    T max = list.get(0);
    for (T item : list) {
        if (item.compareTo(max) > 0) max = item;
    }
    return max;
}

