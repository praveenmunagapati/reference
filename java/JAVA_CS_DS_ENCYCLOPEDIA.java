// --- Abstract class ---
static abstract class Shape {
    /** Every shape has a name. Abstract classes CAN have fields. */
    protected String name;

    Shape(String name) { this.name = name; }

    /** Abstract method — subclasses MUST implement. */
    abstract double area();

    /** Concrete method — inherited as-is. */
    String describe() {
        return String.format("  %s with area=%.4f", name, area());
    }
}

// --- Interface with default method ---
interface Drawable {
    /** Contract method — must be implemented. */
    String draw();

    /** Default method (Java 8+) — provides a fallback implementation. */
    default String getColor() { return "black"; }
}

interface Resizable {
    void resize(double factor);
}

// --- Concrete class: extends ONE abstract class, implements MULTIPLE interfaces ---
static class Circle extends Shape implements Drawable, Resizable {
    private double radius;

    Circle(double radius) {
        super("Circle");         // Call parent constructor
        this.radius = radius;
    }

    @Override
    double area() { return Math.PI * radius * radius; }

    @Override
    public String draw() { return "  Drawing circle with radius " + radius; }

    @Override
    public void resize(double factor) { this.radius *= factor; }

    @Override
    public String toString() {
        return String.format("Circle(radius=%.2f)", radius);
    }
}

static class Rectangle extends Shape implements Drawable {
    private double width, height;

    Rectangle(double w, double h) {
        super("Rectangle");
        this.width = w;
        this.height = h;
    }

    @Override
    double area() { return width * height; }

    @Override
    public String draw() {
        return String.format("  Drawing rectangle %s x %s", width, height);
    }
}

